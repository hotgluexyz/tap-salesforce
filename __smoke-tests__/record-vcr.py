"""Run Salesforce smoke fixtures.

account_pagination_test is a synthetic injection: the two scrubbed account_test
rows are split across two pages with a synthetic continuation URL. Its expected
output was generated by the harness.
"""

import json
import re
from pathlib import Path
from urllib.parse import parse_qsl, urlencode

from faker import Faker
from hotglue_smoke_test.vcr.sanitize import (
    redact_credential,
    sanitize_cassette_file,
    scrub_response_body as sanitize_response_body,
)
from hotglue_smoke_test.vcr.tap import VCRTapTestRunner


class ConnectorTapTestRunner(VCRTapTestRunner):
    # Hide the test org's hostname while keeping config and cassette URLs consistent for replay.
    ANONYMIZED_INSTANCE_URL = "https://salesforce.example.com"

    # X-SFDC-Session carries access tokens; Cookie carries Salesforce browser IDs.
    FILTER_HEADERS = [*VCRTapTestRunner.FILTER_HEADERS, "x-sfdc-session", "cookie"]

    PRESERVE_KEYS = {"Id", "SystemModstamp", "done", "nextRecordsUrl", "query", "totalSize"}

    def scrub_request_body(self, body):
        from hotglue_smoke_test.vcr.sanitize import scrub_request_body

        # Salesforce's OAuth endpoint accepts form data, rather than JSON/XML.
        if body.startswith("grant_type="):
            return urlencode([
                (key, redact_credential(value) if key in self.TOKEN_KEYS else value)
                for key, value in parse_qsl(body, keep_blank_values=True)
            ])
        return scrub_request_body(body, set(self.TOKEN_KEYS))

    def scrub_response_body(self, body, faker, cache):
        preserved = set(self.PRESERVE_KEYS)
        if body.lstrip().startswith("{") and "access_token" in json.loads(body):
            preserved.discard("Id")
        return sanitize_response_body(body, preserved, faker, cache, set(self.TOKEN_KEYS))

    @staticmethod
    def normalize_query(key, value, request):
        # Set iteration order does not change the meaning of an IN list of IDs.
        return re.sub(
            r"\bIN\s*\((\s*'[A-Za-z0-9]+'(?:\s*,\s*'[A-Za-z0-9]+')*\s*)\)",
            lambda match: "IN (" + ",".join(sorted(re.findall(r"'[A-Za-z0-9]+'", match[1]))) + ")",
            value,
        )

    def vcr_use_cassette(self, filter_query_parameters):
        return super().vcr_use_cassette([
            *filter_query_parameters,
            ("q", self.normalize_query),
        ])

    def scrub_uri(self, uri):
        config = json.loads((Path(self.test_case_path) / "config.json").read_text())
        instance_url = config["instance_url"].rstrip("/")
        if uri.startswith(instance_url + "/"):
            return self.ANONYMIZED_INSTANCE_URL + uri[len(instance_url):]
        return uri

    def sanitize_cassette(self):
        faker = Faker()
        Faker.seed(hash(self.test_case) & 0xFFFFFFFF)
        cache = {}
        sanitize_cassette_file(
            self.vcr_cassette_path,
            scrub_response=lambda body: self.scrub_response_body(body, faker, cache),
            scrub_request=self.scrub_request_body,
            scrub_uri=self.scrub_uri,
        )
        config_path = Path(self.test_case_path) / "config.json"
        config = json.loads(config_path.read_text())
        config["instance_url"] = self.ANONYMIZED_INSTANCE_URL
        config_path.write_text(json.dumps(config, indent=4) + "\n")

    def module(self) -> str:
        return "tap_salesforce"

    def launch(self):
        from tap_salesforce import SalesforceTap

        if self.mode == "record":
            config = json.loads((Path(self.test_case_path) / "config.json").read_text())
            if config["instance_url"] == self.ANONYMIZED_INSTANCE_URL:
                raise ValueError("Set the live sandbox instance_url in the case config before recording.")

        # The tap writes its estimated record totals alongside runtime output.
        (Path(self.test_case_path) / "test_runtime").mkdir(parents=True, exist_ok=True)
        SalesforceTap.cli()


if __name__ == "__main__":
    ConnectorTapTestRunner.main()
